#!/usr/bin/env node
// Writes assets/icons.js from the Lucide icons in assets/icons/ (lucide-static 0.468.0, ISC licence, see
// assets/icons/LICENSE): the inner shapes of each SVG, so the decks draw them inline and can trace their strokes.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), 'icons');
const icons = {};
for (const f of readdirSync(DIR).filter((f) => f.endsWith('.svg'))) {
  const svg = readFileSync(join(DIR, f), 'utf8');
  icons[f.replace(/\.svg$/, '')] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
writeFileSync(join(DIR, '..', 'icons.js'), `// Generated by assets/build-icons.mjs from Lucide (https://lucide.dev, ISC licence). Do not edit.\nwindow.ICONS = ${JSON.stringify(icons)};\n`);
console.log(`icons.js · ${Object.keys(icons).join(', ')}`);
