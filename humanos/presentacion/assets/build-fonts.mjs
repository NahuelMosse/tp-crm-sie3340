#!/usr/bin/env node
// Writes assets/fonts.css with the self-hosted faces embedded as data URIs: a browser refuses a font file
// loaded from the file system (origin null), and the decks have to open with a double click, without a server.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const faces = [
  ['Gambarino', 400, 'gambarino-400.woff2'],
  ['General Sans', 400, 'general-sans-400.woff2'],
  ['General Sans', 500, 'general-sans-500.woff2'],
  ['General Sans', 600, 'general-sans-600.woff2'],
];
const css = faces.map(([family, weight, file]) => {
  const b64 = readFileSync(join(HERE, 'fonts', file)).toString('base64');
  return `@font-face { font-family: "${family}"; font-weight: ${weight}; font-display: swap; src: url(data:font/woff2;base64,${b64}) format("woff2"); }`;
}).join('\n');
writeFileSync(join(HERE, 'fonts.css'), `/* Generated by assets/build-fonts.mjs. Gambarino and General Sans by the Indian Type Foundry, ITF Free Font License. */\n${css}\n`);
console.log('fonts.css written');
